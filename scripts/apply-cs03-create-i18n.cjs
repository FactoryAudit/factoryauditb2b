const locales = Object.keys(T);
let changed = 0;
for (const loc of locales) {
  const file = path.join(DIR, `${loc}.json`);
  if (!fs.existsSync(file)) {
    console.error(`SKIP ${loc}: file not found`);
    continue;
  }
  const raw = fs.readFileSync(file, "utf8");
  const json = JSON.parse(raw);
  if (!json.admin || typeof json.admin !== "object") {
    console.error(`SKIP ${loc}: no admin namespace`);
    continue;
  }
  // 幂等：若已存在 create 且内容一致则跳过
  if (json.admin.create && JSON.stringify(json.admin.create) === JSON.stringify(T[loc])) {
    console.log(`OK ${loc}: create already present (skip)`);
    continue;
  }
  json.admin.create = T[loc];
  // 2 空格缩进 + CRLF + 末尾换行
  const out = JSON.stringify(json, null, 2).replace(/\n/g, "\r\n") + "\r\n";
  fs.writeFileSync(file, out, "utf8");
  changed++;
  console.log(`WRITE ${loc}: admin.create added`);
}
console.log(`\nDone. ${changed} file(s) written.`);
