-- Migration 037 —— suppliers.fair_record：广交会（Canton Fair）参展记录
--
-- 为什么需要这一列：
--   139 届广交会官方参展商名录里，34,497 家中有 28,541 家带展位号
--   （形如「箱包|第3期|17.2J48」）。这是**可回溯核验的硬事实** ——
--   同行目录没有、且能由举办方名录复核，是这批档案唯一的差异化内容。
--   此前只存在 outputs/cantonfair_pool.jsonl 里，库内无落点。
--
-- 语义边界（不得扩大）：
--   · 本列只存**举办方名录给出的参展事实**，不存任何推断、评级或营销语。
--   · 每个数组元素 = 一条完整、自述的记录，格式固定：
--       `139th Canton Fair · Phase 3 · Hall 17.2 · Booth J48`
--     前缀带届次是刻意的：同一家可能同时出现在 137 届与 139 届，
--     届次不写进元素就必须再加一列，而届次是这条记录的一部分语义。
--   · 展区中文名（箱包 / 鞋 …）**不入库**：展区已由 industry_code 表达，
--     把 57 个展区名再翻成 9 语是本列负担不起的维护成本。
--   · NULL = 该家不在名录中 / 名录未给展位号。绝不用空串或 "N/A" 顶替。
--
-- 与发布闸门的关系：
--   本列**不参与** supplierCompleteness 判定（不改既有发布规则）。
--   它只在有值时于档案页多渲染一个区块，无值即整块不出现。
-- =============================================================================

alter table public.suppliers
