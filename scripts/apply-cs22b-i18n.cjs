function leaves(o) {
  let n = 0;
  const walk = (x) => {
    if (x && typeof x === "object") {
      if (Array.isArray(x)) x.forEach(walk);
      else Object.values(x).forEach(walk);
    } else n++;
  };
  walk(o);
  return n;
}

function writeKeepEol(file, obj) {
  const original = fs.readFileSync(file, "utf8");
  const crlf = original.includes("\r\n");
  const eol = crlf ? "\r\n" : "\n";
  const text = JSON.stringify(obj, null, 2).replace(/\r\n/g, "\n").replace(/\n/g, eol) + eol;
  fs.writeFileSync(file, text, "utf8");
}

let addedTotal = 0;
for (const loc of LOCALES) {
  const file = path.join(DICT_DIR, `${loc}.json`);
  const dict = JSON.parse(fs.readFileSync(file, "utf8"));
  if (!dict.selfAssessment) dict.selfAssessment = {};
  let added = 0;
  for (const [k, v] of Object.entries(TRANS[loc])) {
    if (dict.selfAssessment[k] === undefined) {
      dict.selfAssessment[k] = v;
      added++;
    }
  }
  writeKeepEol(file, dict);
  addedTotal += added;
  console.log(`${loc}: +${added} keys, leaves=${leaves(dict)}`);
}

// 计算真实 en 叶子数（注入后）
const en = JSON.parse(fs.readFileSync(path.join(DICT_DIR, "en.json"), "utf8"));
const newLeaves = leaves(en);

// 同步 scripts/ 下所有叶子数常量 3028 → newLeaves（与多脚本同源）
const OLD = 3028;
const scriptsDir = path.join(process.cwd(), "scripts");
let replaced = 0;
for (const f of fs.readdirSync(scriptsDir)) {
  if (!/\.(ts|cjs|mjs)$/.test(f)) continue;
  const fp = path.join(scriptsDir, f);
  const txt = fs.readFileSync(fp, "utf8");
  if (txt.includes(String(OLD))) {
    const next = txt.split(String(OLD)).join(String(newLeaves));
    fs.writeFileSync(fp, next, "utf8");
    replaced++;
    console.log(`sync constant ${OLD}→${newLeaves} in ${f}`);
  }
}

