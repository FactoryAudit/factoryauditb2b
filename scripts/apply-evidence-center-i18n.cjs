const LOCALES = ["en", "zh", "zh-TW", "ja", "es", "de", "fr", "pt", "ar"];
const SECTIONS = { en: EN, ...L10N };

let totalAdded = 0;
let totalUpdated = 0;

for (const loc of LOCALES) {
  const file = path.join(DIR, `${loc}.json`);
  const raw = fs.readFileSync(file, "utf8");
  const dict = JSON.parse(raw);
  const had = Boolean(dict.evidenceCenter);
  const next = SECTIONS[loc];

  if (!next) {
    console.error(`[i18n] 缺少 ${loc} 的翻译`);
    process.exit(1);
  }

  // 键集一致性校验（防止某语言漏键导致运行时 undefined）
  const enKeys = Object.keys(EN).sort();
  const locKeys = Object.keys(next).sort();
  if (enKeys.join("|") !== locKeys.join("|")) {
    const missing = enKeys.filter((k) => !locKeys.includes(k));
    const extra = locKeys.filter((k) => !enKeys.includes(k));
    console.error(`[i18n] ${loc} 键集不一致 missing=[${missing}] extra=[${extra}]`);
    process.exit(1);
  }

  // 合并：保留已有键（不覆盖已翻译内容），补齐缺失键
  dict.evidenceCenter = { ...(dict.evidenceCenter ?? {}), ...next };

  // ★ 必须沿用原文件格式：2 空格缩进 + CRLF + 末尾换行。
  //   否则整份字典会被重排成单行，产生数万行 diff 且难以 review。
  const out = JSON.stringify(dict, null, 2).replace(/\n/g, "\r\n") + "\r\n";
  fs.writeFileSync(file, out, "utf8");

  if (had) totalUpdated += 1;
  else totalAdded += 1;
}

console.log(
  `[i18n] evidenceCenter 注入完成：新增 ${totalAdded} 个语言文件，更新 ${totalUpdated} 个`
);
