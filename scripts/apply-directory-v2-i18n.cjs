for (const locale of LOCALES) {
  const file = path.join(DIR, `${locale}.json`);
  const dict = JSON.parse(fs.readFileSync(file, "utf-8"));
  const data = T[locale];
  if (!data) continue;
  let written = 0;
  for (const ns of Object.keys(data)) {
    if (!dict[ns] || typeof dict[ns] !== "object" || Array.isArray(dict[ns])) {
      dict[ns] = {};
    }
    written += applyPatch(dict[ns], data[ns], en[ns]);
  }
  fs.writeFileSync(file, JSON.stringify(dict, null, 2), "utf-8");
  total += written;
  console.log(`${locale}: +${written} keys`);
}
console.log(`done, total +${total} keys written`);
