// ---------- 幂等合并 ----------
// applyPatch(target, patch, enVal)：
//   - 对象递归合并
//   - 叶子键仅当 target 缺失或值===en 值时写入（保护已有手写翻译）
//   - 返回写入的叶子键数
function applyPatch(target, patch, enVal) {
  let written = 0;
  for (const key of Object.keys(patch)) {
    const pv = patch[key];
    const ev = enVal && typeof enVal === "object" ? enVal[key] : undefined;
    if (pv && typeof pv === "object" && !Array.isArray(pv)) {
      if (!target[key] || typeof target[key] !== "object" || Array.isArray(target[key])) {
        target[key] = {};
      }
      written += applyPatch(target[key], pv, ev);
    } else {
      const cur = target[key];
      if (cur === undefined || cur === ev) {
        target[key] = pv;
        written += 1;
      }
    }
  }
  return written;
}

